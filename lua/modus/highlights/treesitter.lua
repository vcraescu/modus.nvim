	local util = require("modus.util")
	local styles = util.get_styles(config)

	return {
		["@annotation"] = { link = "PreProc" },
		["@attribute"] = { fg = c.preprocessor },
		["@attribute.builtin"] = { link = "@attribute" },
		["@boolean"] = { link = "Boolean" },
		["@character"] = { link = "Character" },
		["@character.special"] = { link = "SpecialChar" },
		["@comment"] = { link = "Comment" },
		["@comment.attribute"] = styles.comments({ fg = c.docmarkup }),
		["@comment.documentation"] = { link = "SpecialComment" },
		["@comment.error"] = { link = "Todo" },
		["@comment.hint"] = { link = "Todo" },
		["@comment.info"] = { link = "Todo" },
		["@comment.note"] = { link = "Todo" },
		["@comment.todo"] = { link = "Todo" },
		["@comment.warning"] = { link = "Todo" },
		["@constant"] = { link = "Constant" },
		["@constant.builtin"] = { link = "Constant" },
		["@constant.macro"] = { link = "Macro" },
		["@constructor"] = { link = "Type" },
		["@diff.delta"] = { link = "Changed" },
		["@diff.minus"] = { link = "Removed" },
		["@diff.plus"] = { link = "Added" },
		["@function"] = { link = "Function" },
		["@function.builtin"] = styles.functions({ fg = c.builtin }),
		["@function.call"] = styles.functions({ fg = c.func_call }),
		["@function.macro"] = { link = "Macro" },
		["@function.method"] = { link = "Function" },
		["@function.method.call"] = { link = "@function.call" },
		["@keyword"] = { link = "Keyword" },
		["@keyword.directive"] = { link = "PreProc" },
		["@keyword.directive.define"] = { link = "Define" },
		["@keyword.import"] = { link = "Include" },
		["@label"] = { link = "Label" },
		["@markup"] = { fg = c.fg },
		["@markup.heading"] = { link = "Title" },
		["@markup.heading.1"] = { fg = c.headings[1], bold = true },
		["@markup.heading.2"] = { fg = c.headings[2], bold = true },
		["@markup.heading.3"] = { fg = c.headings[3], bold = true },
		["@markup.heading.4"] = { fg = c.headings[4], bold = true },
